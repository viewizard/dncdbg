enum class FrameType : uint8_t
{
    Unknown,
    CLRNative,
    CLRInternal,
    CLRManaged,
    CLRManagedException,
    CLRManagedExceptionUser
};

bool AllowInternalFrame(ICorDebugInternalFrame *pInternalFrame, bool lastFrames)
{
    CorDebugInternalFrameType corFrameType = STUBFRAME_NONE;
    if (pInternalFrame == nullptr || FAILED(pInternalFrame->GetFrameType(&corFrameType)))
    {
        return false;
    }

    if (lastFrames)
    {
        return corFrameType != STUBFRAME_NONE;
    }

    switch (corFrameType)
    {
    case STUBFRAME_APPDOMAIN_TRANSITION:
    case STUBFRAME_LIGHTWEIGHT_FUNCTION:
    case STUBFRAME_FUNC_EVAL:
    case STUBFRAME_INTERNALCALL:
    case STUBFRAME_CLASS_INIT:
    case STUBFRAME_SECURITY:
    case STUBFRAME_JIT_COMPILATION:
        return true;
    case STUBFRAME_EXCEPTION: // no need to add an `[Exception]` frame at the top of the stack trace
    case STUBFRAME_M2U: // hide managed-to-native transitions in the middle of the stack trace
    case STUBFRAME_U2M: // hide native-to-managed transitions in the middle of the stack trace
    case STUBFRAME_NONE:
        return false;
    default:
        assert(false);
        return false;
    }
}

// Frames of methods or types marked with StackTraceHiddenAttribute are omitted from the stack trace.
bool IsStackTraceHiddenFrame(ICorDebugFrame *pFrame)
{
    ToRelease<ICorDebugFunction> trFunction;
    mdMethodDef methodToken = mdMethodDefNil;
    if (FAILED(pFrame->GetFunction(&trFunction)) ||
        FAILED(pFrame->GetFunctionToken(&methodToken)))
    {
        return false;
    }

    ToRelease<ICorDebugModule> trModule;
    ToRelease<IMetaDataImport> trMDImport;
    if (FAILED(trFunction->GetModule(&trModule)) ||
        FAILED(trModule->GetMetaDataInterface(IID_IMetaDataImport, reinterpret_cast<IUnknown **>(&trMDImport))))
    {
        return false;
    }

    if (HasAttribute(trMDImport, methodToken, DebuggerAttribute::GetStackTraceHidden()))
    {
        return true;
    }

    ToRelease<ICorDebugClass> trClass;
    mdTypeDef typeToken = mdTypeDefNil;
    return SUCCEEDED(trFunction->GetClass(&trClass)) &&
           SUCCEEDED(trClass->GetToken(&typeToken)) &&
           HasAttribute(trMDImport, typeToken, DebuggerAttribute::GetStackTraceHidden());
}

HRESULT GetILOffsetFromNativeAddress(ICorDebugModule *pModule, mdMethodDef methodToken, CORDB_ADDRESS nativeAddress, uint32_t &ilOffset)
{
    if (pModule == nullptr)
    {
        return E_INVALIDARG;
    }

    HRESULT Status = S_OK;
    ToRelease<ICorDebugFunction> trFunction;
    IfFailRet(pModule->GetFunctionFromToken(methodToken, &trFunction));
    ToRelease<ICorDebugCode> trNativeCode;
    IfFailRet(trFunction->GetNativeCode(&trNativeCode));
    CORDB_ADDRESS nativeBaseAddress = 0;
    IfFailRet(trNativeCode->GetAddress(&nativeBaseAddress));
    if (nativeAddress < nativeBaseAddress)
    {
        return E_FAIL; // The address belongs to a different memory region
    }
    const auto nativeOffset = static_cast<uint32_t>(nativeAddress - nativeBaseAddress);

    uint32_t mapElementsCount = 0;
    IfFailRet(trNativeCode->GetILToNativeMapping(0, &mapElementsCount, nullptr));
    if (mapElementsCount == 0)
    {
        return E_FAIL; // Mapping data is unavailable (e.g., lightweight/dynamic methods)
    }

    std::vector<COR_DEBUG_IL_TO_NATIVE_MAP> mapping(mapElementsCount);
    IfFailRet(trNativeCode->GetILToNativeMapping(mapElementsCount, &mapElementsCount, mapping.data()));

    // Search the JIT map to find the IL offset that corresponds to our native offset
    ilOffset = 0;
    uint32_t diff = std::numeric_limits<uint32_t>::max();

    for (uint32_t i = 0; i < mapElementsCount; ++i)
    {
        const auto &entry = mapping.at(i);

        // Skip internal CLR runtime markers that do not map to real IL code:
        // - NO_MAPPING (0xffffffff): Code generated by the CLR (GC checks, security blocks)
        // - PROLOG     (0xfffffffe): Method initialization code
        // - EPILOG     (0xfffffffd): Method return/cleanup code
        if (entry.ilOffset == static_cast<uint32_t>(NO_MAPPING) ||
            entry.ilOffset == static_cast<uint32_t>(PROLOG) ||
            entry.ilOffset == static_cast<uint32_t>(EPILOG))
        {
            continue;
        }

        // Exact match: the native address points precisely to the start of an instruction boundary
        if (entry.nativeStartOffset == nativeOffset)
        {
            ilOffset = entry.ilOffset;
            break;
        }

        // Closest match: the native address most likely points inside an assembly instruction sequence.
        // We keep track of the closest preceding boundary (the 'left' bound of the instruction sequence).
        if (entry.nativeStartOffset <= nativeOffset &&
            diff > nativeOffset - entry.nativeStartOffset)
        {
            ilOffset = entry.ilOffset;
            diff = nativeOffset - entry.nativeStartOffset;
        }
    }

    return S_OK;
}

const char *GetInternalTypeName(CorDebugInternalFrameType frameType)
{
    switch (frameType)
    {
    case STUBFRAME_M2U:
        return "Managed to Native Transition";
    case STUBFRAME_U2M:
        return "Native to Managed Transition";
    case STUBFRAME_APPDOMAIN_TRANSITION:
        return "Appdomain Transition";
    case STUBFRAME_LIGHTWEIGHT_FUNCTION:
        return "Lightweight function";
    case STUBFRAME_FUNC_EVAL:
        return "Func Eval";
    case STUBFRAME_INTERNALCALL:
        return "Internal Call";
    case STUBFRAME_CLASS_INIT:
        return "Class Init";
    case STUBFRAME_EXCEPTION:
        return "Exception";
    case STUBFRAME_SECURITY:
        return "Security";
    case STUBFRAME_JIT_COMPILATION:
        return "JIT Compilation";
    case STUBFRAME_NONE:
        return "Unknown";
    default:
        assert(false);
        return "Unknown";
    }
}

HRESULT GetFrameLocation(ICorDebugFrame *pFrame, ThreadId threadId, FrameLevel level, StackFrame &stackFrame)
{
    HRESULT Status = S_OK;

    std::string displayMethodName;
    if (FAILED(EvalMetadataHelpers::GetFQDisplayRealCodeMethodName(pFrame, displayMethodName)))
    {
        displayMethodName = "[Unnamed managed method in optimized code]";
    }
    stackFrame = StackFrame(threadId, level, displayMethodName);

    ToRelease<ICorDebugFunction> trFunc;
    IfFailRet(pFrame->GetFunction(&trFunc));

    ToRelease<ICorDebugModule> trModule;
    IfFailRet(trFunc->GetModule(&trModule));

    PDB::SequencePoint sp;
    PDB::GlobalFileIndex globalFileIndex;
    if (SUCCEEDED(DebugInfo::GetSequencePointByFrame(pFrame, sp, &globalFileIndex)))
    {
        std::string sourceFilePath;
        std::string algorithm;
        std::string checksum;
        DebugInfo::GetSourceFile(globalFileIndex, sourceFilePath, algorithm, checksum);
        int32_t sourceReference = 0;
        SourceReference::GetSourceReference(globalFileIndex, sourceReference, sourceFilePath);

        stackFrame.source = Source(sourceFilePath, sourceReference);
        if (!algorithm.empty() && !checksum.empty())
        {
            stackFrame.source.checksums.emplace_back(std::move(algorithm), std::move(checksum));
        }
        stackFrame.line = sp.startLine;
        stackFrame.column = sp.startColumn;
        stackFrame.endLine = sp.endLine;
        stackFrame.endColumn = sp.endColumn;
    }

    IfFailRet(Modules::GetModuleMvid(trModule, stackFrame.moduleId));

    return S_OK;
}

// Get the absolute native instruction pointer for the frame.
// JIT-compiled frames implement both ICorDebugILFrame and ICorDebugNativeFrame; the native frame
// provides an offset into the function's native code, which can be resolved to an absolute address.
CORDB_ADDRESS GetFrameNativeIP(ICorDebugFrame *pFrame)
{
    ToRelease<ICorDebugNativeFrame> trNativeFrame;
    if (FAILED(pFrame->QueryInterface(IID_ICorDebugNativeFrame, reinterpret_cast<void **>(&trNativeFrame))))
    {
        return 0;
    }

    uint32_t nativeOffset = 0;
    if (FAILED(trNativeFrame->GetIP(&nativeOffset)))
    {
        return 0;
    }

    ToRelease<ICorDebugFunction> trFunction;
    if (FAILED(pFrame->GetFunction(&trFunction)) || trFunction == nullptr)
    {
        return 0;
    }

    ToRelease<ICorDebugCode> trNativeCode;
    if (FAILED(trFunction->GetNativeCode(&trNativeCode)) || trNativeCode == nullptr)
    {
        return 0;
    }

    CORDB_ADDRESS nativeBaseAddress = 0;
    if (FAILED(trNativeCode->GetAddress(&nativeBaseAddress)))
    {
        return 0;
    }

    return nativeBaseAddress + nativeOffset;
}

using WalkFramesCallback = FunctionRef<HRESULT(FrameType, ICorDebugFrame *, const PDB::SequencePoint *,
                                               const std::string *, const Source *, CORDB_ADDRESS)>;

HRESULT WalkFrames(ICorDebugThread *pThread, const WalkFramesCallback &cb)
{
    HRESULT Status = S_OK;

    const auto exceptionStackTrace = [&]() -> HRESULT
    {
        ToRelease<ICorDebugThread4> trThread4;
        IfFailRet(pThread->QueryInterface(IID_ICorDebugThread4, reinterpret_cast<void **>(&trThread4)));
        // From third-party/diagnostics/src/shared/inc/cordebug.idl
        // Returns S_OK if ICorDebugThread::GetCurrentException() is non-NULL and the exception
        // it refers to has completed the first pass of exception handling without locating
        // a catch clause.
        // Returns S_FALSE if there is no exception, it hasn't completed the first pass handling,
        // or a catch handler was located.
        IfFailRet(trThread4->HasUnhandledException());
        if (Status == S_FALSE)
        {
            return S_OK;
        }

        ToRelease<ICorDebugValue> trExceptionValueRef;
        IfFailRet(pThread->GetCurrentException(&trExceptionValueRef));
        if (trExceptionValueRef == nullptr)
        {
            return E_FAIL;
        }

        ToRelease<ICorDebugValue> trExceptionValue;
        IfFailRet(EvalValueHelpers::DereferenceAndUnboxValue(trExceptionValueRef, &trExceptionValue));
        ToRelease<ICorDebugExceptionObjectValue> trExceptionObjectValue;
        IfFailRet(trExceptionValue->QueryInterface(IID_ICorDebugExceptionObjectValue, reinterpret_cast<void **>(&trExceptionObjectValue)));
        ToRelease<ICorDebugExceptionObjectCallStackEnum> trExceptionObjectCallStackEnum;
        IfFailRet(trExceptionObjectValue->EnumerateExceptionCallStack(&trExceptionObjectCallStackEnum));

        int lastForeignExceptionFrameIndex = -1;
        int index = -1;
        CorDebugExceptionObjectStackFrame exceptionObjectStackFrame;
        ULONG fetched = 0;
        while (SUCCEEDED(trExceptionObjectCallStackEnum->Next(1, &exceptionObjectStackFrame, &fetched)) && fetched == 1)
        {
            exceptionObjectStackFrame.pModule->Release();

            index++;
            if (exceptionObjectStackFrame.isLastForeignExceptionFrame == TRUE)
            {
                lastForeignExceptionFrameIndex = index;
            }
        }
        // Release the first enumerator before reusing the variable for a fresh enumeration.
        trExceptionObjectCallStackEnum.Free();

        // The exception thread was not changed (the exception was not rethrown), so normal unwinding will work without issues.
        if (lastForeignExceptionFrameIndex == -1)
        {
            return S_OK;
        }

        IfFailRet(trExceptionObjectValue->EnumerateExceptionCallStack(&trExceptionObjectCallStackEnum));

        index = -1;
        while (SUCCEEDED(trExceptionObjectCallStackEnum->Next(1, &exceptionObjectStackFrame, &fetched)) && fetched == 1)
        {
            ToRelease<ICorDebugModule> trModule(exceptionObjectStackFrame.pModule);

            index++;
            // Don't unwind stack frames that belong to the current thread, normal unwinding will handle them.
            if (lastForeignExceptionFrameIndex < index)
            {
                break;
            }

            CORDB_ADDRESS modAddress = 0;
            uint32_t ilOffset = 0;
            PDB::SequencePoint sequencePoint;
            std::string sourceFilePath;
            if (FAILED(trModule->GetBaseAddress(&modAddress)) ||
                FAILED(GetILOffsetFromNativeAddress(trModule, exceptionObjectStackFrame.methodDef, exceptionObjectStackFrame.ip, ilOffset)))
            {
                continue;
            }

            std::string displayMethodName;
            if (FAILED(EvalMetadataHelpers::GetFQDisplayRealCodeMethodName(trModule, exceptionObjectStackFrame.methodDef, displayMethodName)))
            {
                displayMethodName = "[Unnamed managed method in optimized code]";
            }

            std::string algorithm;
            std::string checksum;
            if (SUCCEEDED(DebugInfo::GetSequencePointByILOffset(modAddress, exceptionObjectStackFrame.methodDef, ilOffset, sequencePoint)) &&
                SUCCEEDED(DebugInfo::GetSourceFile({modAddress, sequencePoint.sourceFileIndex}, sourceFilePath, algorithm, checksum)))
            {
                int32_t sourceReference = 0;
                SourceReference::GetSourceReference({modAddress, sequencePoint.sourceFileIndex}, sourceReference, sourceFilePath);

                Source source(sourceFilePath, sourceReference);
                source.checksums.emplace_back(std::move(algorithm), std::move(checksum));
                if (cb(FrameType::CLRManagedExceptionUser, nullptr, &sequencePoint, &displayMethodName,
                       &source, exceptionObjectStackFrame.ip) == S_CAN_EXIT)
                {
                    return S_CAN_EXIT;
                }
            }
            // Make sure that the last foreign exception frame itself is added to the stack trace.
            else if (exceptionObjectStackFrame.isLastForeignExceptionFrame == TRUE)
            {
                if (cb(FrameType::CLRManagedException, nullptr, nullptr, &displayMethodName,
                       nullptr, exceptionObjectStackFrame.ip) == S_CAN_EXIT)
                {
                    return S_CAN_EXIT;
                }
            }
        }

        return S_OK;
    };
    // Exception stack trace goes first, since foreign exception frames must be the upper frames of the stack trace.
    if (exceptionStackTrace() == S_CAN_EXIT)
    {
        return S_OK;
    }

    // Enumerate all stack chains of the thread, starting at the active (most recent) one.
    ToRelease<ICorDebugChainEnum> trChainEnum;
    IfFailRet(pThread->EnumerateChains(&trChainEnum));

    // ICorDebugChain::EnumerateFrames() reports internal frames inline. Internal frames that are not
    // followed by any regular frame belong to the root end of the stack trace and are reported
    // differently (see AllowInternalFrame()). Since the enumerator is forward-only, internal frames
    // are buffered until the next regular frame is known.
    std::list<ToRelease<ICorDebugInternalFrame>> trPendingInternalFrames;
    ToRelease<ICorDebugFrameEnum> trFrameEnum;

    for (;;)
    {
        // Fetch the next regular (non-internal) frame, buffering internal frames into trPendingInternalFrames.
        ToRelease<ICorDebugFrame> trFrame;
        bool frameFetched = false;
        for (;;)
        {
            if (trFrameEnum == nullptr)
            {
                // Move to the next managed chain.
                ToRelease<ICorDebugChain> trChain;
                ULONG fetchedChains = 0;
                if (FAILED(trChainEnum->Next(1, &trChain, &fetchedChains)) || fetchedChains == 0)
                {
                    break; // End of stack.
                }
                if (trChain == nullptr)
                {
                    continue;
                }

                BOOL isManaged = FALSE;
                if (FAILED(trChain->IsManaged(&isManaged)) || isManaged == FALSE)
                {
                    continue; // Skip unmanaged chains, they are always empty.
                }

                if (FAILED(trChain->EnumerateFrames(&trFrameEnum)))
                {
                    continue; // Skip chains that failed to enumerate frames.
                }
                continue; // Proceed with frame enumeration.
            }

            ToRelease<ICorDebugFrame> trNextFrame;
            ULONG fetchedFrames = 0;
            if (FAILED(trFrameEnum->Next(1, &trNextFrame, &fetchedFrames)))
            {
                break; // Stop the walk on enumeration errors.
            }
            if (fetchedFrames == 0)
            {
                trFrameEnum.Free(); // Current chain exhausted, move to the next chain.
                continue;
            }
            if (trNextFrame == nullptr)
            {
                continue; // Skip null frames, if any.
            }

            ToRelease<ICorDebugInternalFrame> trInternalFrame;
            if (SUCCEEDED(trNextFrame->QueryInterface(IID_ICorDebugInternalFrame, reinterpret_cast<void **>(&trInternalFrame))))
            {
                trPendingInternalFrames.emplace_back(trInternalFrame.Detach());
                continue;
            }

            trFrame = trNextFrame.Detach();
            frameFetched = true;
            break;
        }

        if (!frameFetched)
        {
            break; // End of stack.
        }

        // Internal frames positioned before the current regular frame belong to the middle of the stack trace.
        for (const auto &trInternalFrame : trPendingInternalFrames)
        {
            if (AllowInternalFrame(trInternalFrame, false))
            {
                if (cb(FrameType::CLRInternal, trInternalFrame, nullptr, nullptr, nullptr, 0) == S_CAN_EXIT)
                {
                    return S_OK;
                }
            }
        }
        trPendingInternalFrames.clear();

        // If this is a RuntimeUnwindableFrame, it is a native stack frame that requires special
        // unwinding help from the runtime and cannot be inspected as a managed frame.
        ToRelease<ICorDebugRuntimeUnwindableFrame> trRuntimeUnwindableFrame;
        if (SUCCEEDED(trFrame->QueryInterface(IID_ICorDebugRuntimeUnwindableFrame, reinterpret_cast<void **>(&trRuntimeUnwindableFrame))))
        {
            continue;
        }

        ToRelease<ICorDebugILFrame> trILFrame;
        if (SUCCEEDED(trFrame->QueryInterface(IID_ICorDebugILFrame, reinterpret_cast<void **>(&trILFrame))))
        {
            uint32_t tmpOffset = 0;
            CorDebugMappingResult mappingResult = MAPPING_NO_INFO;
            if (SUCCEEDED(trILFrame->GetIP(&tmpOffset, &mappingResult)) &&
                (mappingResult == MAPPING_UNMAPPED_ADDRESS ||
                 mappingResult == MAPPING_NO_INFO))
            {
                // Related to ICorDebugInternalFrame, ignore it.
                continue;
            }

            // Hide state machine related frames for both JMC and non-JMC cases.
            std::string displayMethodName;
            ToRelease<ICorDebugFunction> trFunction;
            if ((SUCCEEDED(trFrame->GetFunction(&trFunction)) && DebugInfo::IsStateMachineKickoffMethod(trFunction)) ||
                (SUCCEEDED(EvalMetadataHelpers::GetFQDisplayRealCodeMethodName(trFrame, displayMethodName)) &&
                 // Note: starts_with() is C++20, use rfind() for compatibility
                 (displayMethodName.rfind("System.Runtime.CompilerServices.AsyncMethodBuilderCore", 0) == 0 ||
                  displayMethodName.rfind("System.Runtime.CompilerServices.AsyncTaskMethodBuilder", 0) == 0)))
            {
                continue;
            }

            // Hide frames marked with System.Diagnostics.StackTraceHiddenAttribute.
            if (IsStackTraceHiddenFrame(trFrame))
            {
                continue;
            }

            if (cb(FrameType::CLRManaged, trFrame, nullptr, nullptr, nullptr, GetFrameNativeIP(trFrame)) == S_CAN_EXIT)
            {
                return S_OK;
            }

            continue;
        }

        ToRelease<ICorDebugNativeFrame> trNativeFrame;
        if (SUCCEEDED(trFrame->QueryInterface(IID_ICorDebugNativeFrame, reinterpret_cast<void **>(&trNativeFrame))))
        {
            if (cb(FrameType::CLRNative, nullptr, nullptr, nullptr, nullptr, 0) == S_CAN_EXIT)
            {
                return S_OK;
            }

            continue;
        }

        if (cb(FrameType::Unknown, nullptr, nullptr, nullptr, nullptr, 0) == S_CAN_EXIT)
        {
            return S_OK;
        }
    }

    // Internal frames that were not followed by any regular frame belong to the root end of the stack trace.
    for (const auto &trInternalFrame : trPendingInternalFrames)
    {
        if (AllowInternalFrame(trInternalFrame, true))
        {
            if (cb(FrameType::CLRInternal, trInternalFrame, nullptr, nullptr, nullptr, 0) == S_CAN_EXIT)
            {
                return S_OK;
            }
        }
    }

    return S_OK;
}

