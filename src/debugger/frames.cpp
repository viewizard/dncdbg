HRESULT GetFrameAt(ICorDebugThread *pThread, FrameLevel level, ICorDebugFrame **ppFrame)
{
    const auto foreignExceptionFrameDetected = [&]() -> bool
    {
        HRESULT Status = S_OK;
        ToRelease<ICorDebugThread4> trThread4;
        if (FAILED(pThread->QueryInterface(IID_ICorDebugThread4, reinterpret_cast<void **>(&trThread4))) ||
            FAILED(Status = trThread4->HasUnhandledException()) ||
            Status == S_FALSE)
        {
            return false;
        }

        ToRelease<ICorDebugValue> trExceptionValueRef;
        if (FAILED(pThread->GetCurrentException(&trExceptionValueRef)) ||
            trExceptionValueRef == nullptr)
        {
            return false;
        }

        ToRelease<ICorDebugValue> trExceptionValue;
        ToRelease<ICorDebugExceptionObjectValue> trExceptionObjectValue;
        if (FAILED(EvalValueHelpers::DereferenceAndUnboxValue(trExceptionValueRef, &trExceptionValue)) ||
            FAILED(trExceptionValue->QueryInterface(IID_ICorDebugExceptionObjectValue, reinterpret_cast<void **>(&trExceptionObjectValue))))
        {
            return false;
        }

        CorDebugExceptionObjectStackFrame exceptionObjectStackFrame;
        ULONG fetched = 0;
        ToRelease<ICorDebugExceptionObjectCallStackEnum> trExceptionObjectCallStackEnum;
        if (FAILED(trExceptionObjectValue->EnumerateExceptionCallStack(&trExceptionObjectCallStackEnum)))
        {
            return false;
        }

        while (SUCCEEDED(trExceptionObjectCallStackEnum->Next(1, &exceptionObjectStackFrame, &fetched)) && fetched == 1)
        {
            exceptionObjectStackFrame.pModule->Release();

            if (exceptionObjectStackFrame.isLastForeignExceptionFrame == TRUE)
            {
                return true;
            }
        }

        return false;
    };

    const bool justMyCode = Config::GetJustMyCode();

    // Try to get frame 0 (the current active frame) in an efficient way, if possible.
    // Note: This optimization is only valid when JMC is disabled, because when JMC is enabled,
    // the active frame might be external code (non-user code) and should not be returned directly.
    if (!justMyCode && static_cast<int>(level) == 0 && !foreignExceptionFrameDetected() &&
        SUCCEEDED(pThread->GetActiveFrame(ppFrame)) && *ppFrame != nullptr)
    {
        return S_OK;
    }

    const int stackTraceLimit = static_cast<int>(Config::GetStackTraceLimit());
    int currentFrame = -1;
    bool prevFrameExternal = false;

    WalkFrames(pThread,
        [&](FrameType frameType, ICorDebugFrame *pFrame, const PDB::SequencePoint *,
            const std::string *, const Source *, CORDB_ADDRESS) -> HRESULT
        {
            if (justMyCode && frameType != FrameType::CLRManagedExceptionUser)
            {
                ToRelease<ICorDebugFunction> trFunction;
                ToRelease<ICorDebugFunction2> trFunction2;
                BOOL JMCStatus = FALSE;
                if (frameType == FrameType::CLRManaged &&
                    SUCCEEDED(pFrame->GetFunction(&trFunction)) &&
                    SUCCEEDED(trFunction->QueryInterface(IID_ICorDebugFunction2, reinterpret_cast<void **>(&trFunction2))) &&
                    SUCCEEDED(trFunction2->GetJMCStatus(&JMCStatus)) &&
                    JMCStatus == TRUE)
                {
                    prevFrameExternal = false;
                }
                else
                {
                    if (!prevFrameExternal)
                    {
                        currentFrame++;
                        prevFrameExternal = true;
                    }
                    return S_OK; // Return success to continue walking.
                }
            }

            currentFrame++;

            if (currentFrame < static_cast<int>(level))
            {
                return S_OK; // Return success to continue walking.
            }
            else if (currentFrame >= stackTraceLimit ||
                     currentFrame > static_cast<int>(level) ||
                     frameType != FrameType::CLRManaged)
            {
                return S_CAN_EXIT; // Fast exit from the loop.
            }

            pFrame->AddRef();
            *ppFrame = pFrame;
            return S_CAN_EXIT; // Fast exit from the loop.
        });

    return *ppFrame != nullptr ? S_OK : E_FAIL;
}

HRESULT GetStackFrames(ICorDebugThread *pThread, ThreadId threadId, FrameLevel startFrame, unsigned maxFrames,
                       std::vector<StackFrame> &stackFrames)
{
    // CoreCLR native frame, which could be part of a transition to at least one user native frame.
    static const std::string FrameCLRNativeText = "[CLR Native Frame]";
    // This frame usually indicates some failure during managed unwinding.
    static const std::string FrameUnknownText = "[Unknown Frame]";
    // Non-user code frame when Just My Code is enabled.
    static const std::string ExternalCodeText = "[External Code]";
    // Prefix for foreign exception stack frames (frames from a rethrown exception's original thread).
    static const std::string ExceptionFramePrefix = "[Exception] ";
    // Marks that the stack trace was truncated.
    static const std::string TruncatedStackTrace = "[Truncated Stack Trace]";

    const int stackTraceLimit = static_cast<int>(Config::GetStackTraceLimit());
    bool stackTruncated = false;
    const bool justMyCode = Config::GetJustMyCode();
    int currentFrame = -1;
    bool prevFrameExternal = false;

    WalkFrames(pThread,
        [&](FrameType frameType, ICorDebugFrame *pFrame, const PDB::SequencePoint *pSequencePoint,
            const std::string *pMethodName, const Source *pSource, CORDB_ADDRESS ip) -> HRESULT
        {
            if (justMyCode && frameType != FrameType::CLRManagedExceptionUser)
            {
                ToRelease<ICorDebugFunction> trFunction;
                ToRelease<ICorDebugFunction2> trFunction2;
                BOOL JMCStatus = FALSE;
                if (frameType == FrameType::CLRManaged &&
                    SUCCEEDED(pFrame->GetFunction(&trFunction)) &&
                    SUCCEEDED(trFunction->QueryInterface(IID_ICorDebugFunction2, reinterpret_cast<void **>(&trFunction2))) &&
                    SUCCEEDED(trFunction2->GetJMCStatus(&JMCStatus)) &&
                    JMCStatus == TRUE)
                {
                    prevFrameExternal = false;
                }
                else
                {
                    if (!prevFrameExternal)
                    {
                        currentFrame++;
                        stackFrames.emplace_back(threadId, FrameLevel{currentFrame}, ExternalCodeText);
                        stackFrames.back().presentationHint = "subtle";
                        prevFrameExternal = true;
                    }
                    return S_OK; // Return success to continue walking.
                }
            }

            currentFrame++;

            if (currentFrame < static_cast<int>(startFrame))
            {
                return S_OK; // Return success to continue walking.
            }
            if (maxFrames != 0 && currentFrame >= static_cast<int>(startFrame) + static_cast<int>(maxFrames))
            {
                return S_CAN_EXIT; // Fast exit from the loop.
            }
            if (currentFrame >= stackTraceLimit)
            {
                stackTruncated = true;
                return S_CAN_EXIT; // Fast exit from the loop.
            }

            switch (frameType)
            {
            case FrameType::Unknown:
                stackFrames.emplace_back(threadId, FrameLevel{currentFrame}, FrameUnknownText);
                stackFrames.back().presentationHint = "subtle";
                break;
            case FrameType::CLRNative:
                stackFrames.emplace_back(threadId, FrameLevel{currentFrame}, FrameCLRNativeText);
                stackFrames.back().presentationHint = "subtle";
                break;
            case FrameType::CLRInternal:
            {
                ToRelease<ICorDebugInternalFrame> trInternalFrame;
                CorDebugInternalFrameType corFrameType = STUBFRAME_NONE;
                if (SUCCEEDED(pFrame->QueryInterface(IID_ICorDebugInternalFrame, reinterpret_cast<void **>(&trInternalFrame))))
                {
                    trInternalFrame->GetFrameType(&corFrameType);
                }
                std::string name = "[";
                name += GetInternalTypeName(corFrameType);
                name += ']';
                stackFrames.emplace_back(threadId, FrameLevel{currentFrame}, name);
                stackFrames.back().presentationHint = "subtle";
                break;
            }
            case FrameType::CLRManaged:
            {
                StackFrame stackFrame;
                GetFrameLocation(pFrame, threadId, FrameLevel{currentFrame}, stackFrame);
                if (ip != 0)
                {
                    stackFrame.instructionPointerReference = MetadataHelpers::AddrToString(ip);
                }
                stackFrame.presentationHint = "normal";
                stackFrames.push_back(stackFrame);
                break;
            }
            case FrameType::CLRManagedException:
            case FrameType::CLRManagedExceptionUser:
            {
                stackFrames.emplace_back(threadId, FrameLevel{currentFrame}, ExceptionFramePrefix + *pMethodName);
                stackFrames.back().presentationHint = "normal";
                if (frameType == FrameType::CLRManagedExceptionUser)
                {
                    stackFrames.back().source = *pSource;
                    stackFrames.back().line = pSequencePoint->startLine;
                    stackFrames.back().endLine = pSequencePoint->endLine;
                }
                if (ip != 0)
                {
                    stackFrames.back().instructionPointerReference = MetadataHelpers::AddrToString(ip);
                }
                break;
            }
            }

            return S_OK; // Return success to continue walking.
        });

    if (stackTruncated)
    {
        stackFrames.emplace_back(threadId, FrameLevel{currentFrame}, TruncatedStackTrace);
        stackFrames.back().presentationHint = "subtle";
    }

    return S_OK;
}

